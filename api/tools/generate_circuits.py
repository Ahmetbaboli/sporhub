"""Generate web/lib/circuits.ts: SVG outlines of F1 circuits keyed by Jolpica circuitId.

    PYTHONPATH=. uv run python tools/generate_circuits.py

Source: bacinger/f1-circuits (MIT, (c) 2019-2025 Tomislav Bacinger), GeoJSON track lines.
The Jolpica -> dataset mapping is an explicit table (never matched by name similarity);
a circuit missing here simply has no outline and the UI shows its fallback.
"""

import json
import math
import sys
from pathlib import Path
from typing import Any

import httpx

from app.core.tls import ssl_context

BASE_URL = "https://raw.githubusercontent.com/bacinger/f1-circuits/master/circuits/"
OUTPUT = Path(__file__).resolve().parents[2] / "web" / "lib" / "circuits.ts"
VIEW_SIZE = 100.0
PADDING = 4.0
MIN_STEP = 0.6  # drop points closer than this (viewBox units) to keep the file small
TIMEOUT_SECONDS = 30

# Jolpica circuitId -> bacinger/f1-circuits file id (country code + first-race year).
JOLPICA_TO_DATASET: dict[str, str] = {
    "albert_park": "au-1953",
    "americas": "us-2012",
    "bahrain": "bh-2002",
    "baku": "az-2016",
    "catalunya": "es-1991",
    "hungaroring": "hu-1986",
    "imola": "it-1953",
    "interlagos": "br-1940",
    "jeddah": "sa-2021",
    "losail": "qa-2004",
    "madring": "es-2026",
    "marina_bay": "sg-2008",
    "miami": "us-2022",
    "monaco": "mc-1929",
    "monza": "it-1922",
    "red_bull_ring": "at-1969",
    "rodriguez": "mx-1962",
    "sepang": "my-1999",
    "shanghai": "cn-2004",
    "silverstone": "gb-1948",
    "spa": "be-1925",
    "suzuka": "jp-1962",
    "vegas": "us-2023",
    "villeneuve": "ca-1978",
    "yas_marina": "ae-2009",
    "zandvoort": "nl-1948",
}


def track_points(geojson: dict[str, Any]) -> list[tuple[float, float]]:
    geometry = geojson["features"][0]["geometry"]
    coords = geometry["coordinates"]
    if geometry["type"] == "MultiLineString":
        coords = [point for line in coords for point in line]
    return [(float(lon), float(lat)) for lon, lat, *_ in coords]


def project(points: list[tuple[float, float]]) -> list[tuple[float, float]]:
    """Equirectangular projection around the track's mean latitude, y pointing down."""
    mean_lat = math.radians(sum(lat for _, lat in points) / len(points))
    return [(lon * math.cos(mean_lat), -lat) for lon, lat in points]


def fit(points: list[tuple[float, float]]) -> tuple[list[tuple[float, float]], float, float]:
    xs, ys = [x for x, _ in points], [y for _, y in points]
    span = max(max(xs) - min(xs), max(ys) - min(ys))
    scale = (VIEW_SIZE - 2 * PADDING) / span
    fitted = [((x - min(xs)) * scale + PADDING, (y - min(ys)) * scale + PADDING) for x, y in points]
    width = (max(xs) - min(xs)) * scale + 2 * PADDING
    height = (max(ys) - min(ys)) * scale + 2 * PADDING
    return fitted, width, height


def thin(points: list[tuple[float, float]]) -> list[tuple[float, float]]:
    kept = [points[0]]
    for point in points[1:]:
        if math.dist(point, kept[-1]) >= MIN_STEP:
            kept.append(point)
    return kept


def svg_path(points: list[tuple[float, float]]) -> str:
    head, *rest = points
    return f"M{head[0]:.1f} {head[1]:.1f}" + "".join(f"L{x:.1f} {y:.1f}" for x, y in rest) + "Z"


def outline(client: httpx.Client, dataset_id: str) -> dict[str, str]:
    response = client.get(f"{BASE_URL}{dataset_id}.geojson")
    response.raise_for_status()
    fitted, width, height = fit(project(track_points(response.json())))
    return {"viewBox": f"0 0 {width:.1f} {height:.1f}", "path": svg_path(thin(fitted))}


def render(outlines: dict[str, dict[str, str]]) -> str:
    body = json.dumps(outlines, indent=2, sort_keys=True)
    return (
        "// Generated by api/tools/generate_circuits.py. Do not edit by hand.\n"
        "// Track outlines: bacinger/f1-circuits, MIT License, (c) 2019-2025 Tomislav Bacinger.\n"
        "// Keyed by Jolpica circuitId through an explicit table (no name matching).\n\n"
        "export interface CircuitOutline {\n  viewBox: string;\n  path: string;\n}\n\n"
        f"export const CIRCUITS: Record<string, CircuitOutline> = {body};\n"
    )


def main() -> int:
    outlines: dict[str, dict[str, str]] = {}
    with httpx.Client(verify=ssl_context(), timeout=TIMEOUT_SECONDS) as client:
        for circuit_id, dataset_id in sorted(JOLPICA_TO_DATASET.items()):
            outlines[circuit_id] = outline(client, dataset_id)
            print(f"{circuit_id:<14} <- {dataset_id}")
    OUTPUT.write_text(render(outlines), encoding="utf-8", newline="\n")
    print(f"wrote {len(outlines)} outlines to {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
